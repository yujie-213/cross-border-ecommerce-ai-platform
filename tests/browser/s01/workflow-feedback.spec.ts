import {test,expect} from '../../../frontend/node_modules/@playwright/test/index.mjs'
import {mkdirSync,writeFileSync} from 'node:fs'
import path from 'node:path'
const root=path.resolve(import.meta.dirname,'../../..'),out=path.join(root,'docs/evidence/S01-WORKFLOW-20261115')
test.use({storageState:path.join(root,'data/private/local-platform/workflow-browser-state.json'),actionTimeout:15000})
test('真实页面的受控失败注入：分析失败、AI不可用及ERP读取失败',async({page})=>{
 test.skip(process.env.S01_WORKFLOW_LIVE!=='1','Explicit existing real session required')
 test.setTimeout(180000);mkdirSync(path.join(out,'screenshots'),{recursive:true})
 await page.goto('/#/home')
 const history=await (await page.request.get('/api/v1/s01/v2/batches')).json()
 const batch=history.items.find((r:any)=>r.state==='SUCCEEDED' && r.analysisRange==='OWNED_REGISTERED').taskRef.taskId
 const list=await (await page.request.get(`/api/v1/s01/v2/batches/${batch}/items?limit=50`)).json()
 const item=list.items.find((r:any)=>r.sku==='HLX-LAMP-SURGE')
 await page.goto(`/#/sku/${item.entityKey}?batch=${batch}`);await expect(page.locator('.product-header')).toContainText(item.sku)
 await page.route('**/api/v1/s01/v2/singles',async r=>{if(r.request().method()==='POST')await r.fulfill({status:202,json:{taskRef:{taskId:'ui-failed-injection'}}});else await r.continue()})
 await page.route('**/api/v1/s01/v2/singles/ui-failed-injection',r=>r.fulfill({json:{task:{taskRef:{taskId:'ui-failed-injection'},state:'FAILED',errorCode:'ERP_AUTH_REJECTED'},report:null}}))
 await page.getByRole('button',{name:'更新补货分析',exact:true}).click()
 await expect(page.getByRole('region',{name:'AI 行动建议'})).toHaveAttribute('data-state','failed')
 await expect(page.getByRole('button',{name:'重试 AI 建议',exact:true})).toBeEnabled()
 await expect(page.getByRole('button',{name:'更新补货分析',exact:true})).toBeEnabled()
 await page.screenshot({path:path.join(out,'screenshots/14-injected-analysis-failure.png'),fullPage:true})
 await page.unrouteAll({behavior:'wait'})
 const singles=await (await page.request.get('/api/v1/s01/v2/singles')).json()
 const real=singles.items.find((r:any)=>r.sku==='HLX-LAMP-SURGE' && r.state==='SUCCEEDED')
 const payload=await (await page.request.get(`/api/v1/s01/v2/singles/${real.taskRef.taskId}`)).json()
 payload.report.analysisReport.ai={status:'UNAVAILABLE',reason:'MODEL_TIMEOUT'}
 await page.route(`**/api/v1/s01/v2/singles/${real.taskRef.taskId}`,r=>r.fulfill({json:payload}))
 await page.goto(`/#/sku/${item.entityKey}?batch=${batch}&single=${real.taskRef.taskId}`)
 await expect(page.getByRole('region',{name:'AI 行动建议'})).toHaveAttribute('data-state','failed')
 await expect(page.getByRole('region',{name:'AI 行动建议'})).toContainText('响应超时')
 await page.screenshot({path:path.join(out,'screenshots/15-injected-ai-unavailable.png'),fullPage:true})
 await page.unrouteAll({behavior:'wait'})
 await page.goto('/#/requisitions');await expect(page.locator('tbody tr')).toHaveCount(3,{timeout:90000})
 await expect(page.getByRole('button',{name:'刷新 ERP 状态'})).toBeEnabled({timeout:90000})
 await page.route('**/api/v1/s01/v2/purchase-status?*',r=>r.fulfill({status:503,json:{code:'ERP_UNAVAILABLE'}}))
 await page.getByRole('button',{name:'刷新 ERP 状态'}).click()
 await expect(page.getByRole('alert')).toContainText('上次结果')
 await expect(page.locator('tbody tr')).toHaveCount(3)
 await expect(page.locator('tbody tr').first()).toContainText('状态待核对')
 await page.screenshot({path:path.join(out,'screenshots/16-injected-erp-read-failure.png'),fullPage:true})
 writeFileSync(path.join(out,'feedback-injection-result.json'),JSON.stringify({result:'PASS',nature:'CONTROLLED_BROWSER_RESPONSE_INJECTION_NOT_REAL_ERP_FAILURE',databaseWrites:0,modelCalls:0,coverage:['analysis retry visible','AI unavailable reason','ERP previous status explicitly stale']},null,2))
})
