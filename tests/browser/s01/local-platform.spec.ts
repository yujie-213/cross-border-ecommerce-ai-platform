import { test, expect } from '../../../frontend/node_modules/@playwright/test/index.mjs'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import path from 'node:path'
const root = path.resolve(import.meta.dirname, '../../..'), privateDir = path.join(root, 'data/private/local-platform')
const screenshots = path.join(root, 'docs/evidence/S01-LOCAL/screenshots')
const statePath = path.join(privateDir, 'browser-state.json')

test('LOCAL PASSWORD: real daily launcher login, logout, history, safe confirmation and manual read-only ERP batch', async ({ page }) => {
  test.skip(process.env.S01_LOCAL_BROWSER !== 'login', 'Explicit local password and teaching readonly verification required')
  test.setTimeout(400000)
  const password = process.env.S01_LOCAL_PASSWORD!; expect(!!password).toBe(true)
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message)); mkdirSync(screenshots, { recursive: true })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '登录智慧电商平台', exact: true })).toBeVisible()
  await expect(page.getByLabel('短期身份令牌')).toHaveCount(0)
  await page.screenshot({ path: path.join(screenshots, 'login.png'), fullPage: true })
  await page.getByLabel('密码', { exact: true }).fill('fixture-intentionally-wrong-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('账号或密码不正确')
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '采购运营工作台', exact: true })).toBeVisible()
  const cookies = await page.context().cookies(), session = cookies.find(c => c.name === 'commerce_session')!
  expect(session.httpOnly).toBe(true); expect(session.sameSite).toBe('Strict'); expect(session.expires - Date.now() / 1000).toBeGreaterThan(28770)
  await expect(page.getByRole('button', { name: '连接身份', exact: true })).toHaveCount(0)
  const old = JSON.parse(readFileSync(path.join(root, 'data/private/s01-v2-local/browser-full-result.json'), 'utf8'))
  await page.getByRole('row').filter({ hasText: old.singleId }).getByRole('button', { name: '查看 SKU', exact: true }).click()
  await expect(page.getByText('已提交 ERP，待领导审批', { exact: true })).toBeVisible()
  const saved = await (await page.request.get(`/api/v1/s01/v2/singles/${old.singleId}/requisition`)).json()
  expect(saved.erpId).toBe('1426'); expect(saved.finalQuantity).toBe(40)
  const rejected = await page.request.post(`/api/v1/s01/v2/singles/${old.singleId}/requisition`, { headers: { Origin: 'http://localhost:5173', 'X-CSRF-Token': cookies.find(c => c.name === 'commerce_csrf')!.value, 'Idempotency-Key': 'local-reject-unacknowledged' }, data: { finalQuantity: 40, sourceAcknowledged: false } })
  expect(rejected.status()).toBe(422)
  await page.getByRole('button', { name: '退出会话', exact: true }).click()
  await expect(page.getByRole('heading', { name: '登录智慧电商平台', exact: true })).toBeVisible()
  expect((await page.request.get('/api/v1/session')).status()).toBe(401)
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '采购运营工作台', exact: true })).toBeVisible()
  const accepted = page.waitForResponse(r => r.url().endsWith('/s01/v2/batches') && r.request().method() === 'POST')
  await page.getByRole('button', { name: '重新检查全部 SKU', exact: true }).click()
  const task = await (await accepted).json(), bid = task.taskRef.taskId
  writeFileSync(path.join(privateDir, 'readonly-batch.json'), JSON.stringify(task, null, 2))
  let progress: any
  await expect.poll(async () => { progress = await (await page.request.get(`/api/v1/s01/v2/batches/${bid}`)).json(); return progress.task.state }, { timeout: 260000, intervals: [2000] }).toBe('SUCCEEDED')
  expect(progress.enumerationComplete).toBe(true); expect(progress.summary.unfinished).toBe(0)
  const all: any[] = []
  for (let offset = 0; offset < progress.summary.scopeObjectCount; offset += 100) all.push(...(await (await page.request.get(`/api/v1/s01/v2/batches/${bid}/items?limit=100&offset=${offset}`)).json()).items)
  expect(new Set(all.map(r => r.entityKey)).size).toBe(progress.summary.scopeObjectCount)
  expect(new Set(all.map(r => r.sku)).size).toBe(progress.summary.discoveredSkuCount)
  await page.getByRole('button', { name: '刷新状态', exact: true }).click()
  await page.getByLabel('SKU / 商品', { exact: true }).fill('YF-SO-QD-S')
  await page.getByRole('row').filter({ hasText: 'YF-SO-QD-S' }).getByRole('button', { name: '查看', exact: true }).click()
  await page.reload(); await expect(page.getByRole('heading', { name: '采购运营工作台', exact: true })).toBeVisible()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: path.join(screenshots, 'workbench.png'), fullPage: true })
  await page.context().storageState({ path: statePath })
  expect(errors).toEqual([])
  writeFileSync(path.join(privateDir, 'browser-login-result.json'), JSON.stringify({ result: 'PASS', batchId: bid, summary: progress.summary, enumerationComplete: progress.enumerationComplete, sourceLimits: progress.sourceLimits, existingRequisitionId: saved.erpId, wrongPasswordRejected: true, logoutRevoked: true, acknowledgementStillRequired: true, pageErrors: errors, newModels: 0, newERPBusinessWrites: 0 }, null, 2))
})

test('LOCAL RESTORE: closed browser and restarted services restore persistent session and existing reports', async ({ browser }) => {
  test.skip(process.env.S01_LOCAL_BROWSER !== 'restore', 'Existing private browser session and restarted launcher required')
  const context = await browser.newContext({ storageState: statePath })
  const page = await context.newPage(); await page.goto('http://localhost:5173/')
  await expect(page.getByRole('heading', { name: '采购运营工作台', exact: true })).toBeVisible()
  const previous = JSON.parse(readFileSync(path.join(privateDir, 'browser-login-result.json'), 'utf8'))
  await page.getByRole('row').filter({ hasText: previous.batchId }).getByRole('button', { name: '打开批次', exact: true }).click()
  await expect(page.getByText(String(previous.summary.scopeObjectCount), { exact: true })).toBeVisible()
  await page.evaluate(() => window.scrollTo(0, 0)); await page.screenshot({ path: path.join(screenshots, 'restored.png'), fullPage: true })
  await context.storageState({ path: statePath }); await context.close()
  writeFileSync(path.join(privateDir, 'browser-restore-result.json'), JSON.stringify({ result: 'PASS', reusedCookieWithoutPassword: true, sameBatchId: previous.batchId, newModels: 0, newERPBusinessWrites: 0 }, null, 2))
})

