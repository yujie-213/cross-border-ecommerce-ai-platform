import { test, expect } from '../../../frontend/node_modules/@playwright/test/index.mjs'
import { mkdirSync } from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

// Real browser over local HTML; all business interactions are explicitly simulated.
const root = path.resolve(import.meta.dirname, '../../..')
const entry = pathToFileURL(path.join(root, 'prototypes/b-after-sales/index.html')).href
const screenshots = path.join(root, 'docs/evidence/B-START-20261116/screenshots')
let errors: string[]
let external: string[]
test.beforeEach(async ({ page }) => {
  mkdirSync(screenshots, { recursive: true })
  errors = []; external = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
  page.on('request', r => { if (!r.url().startsWith('file:')) external.push(r.url()) })
  await page.goto(entry)
})
test.afterEach(async () => {
  expect(errors, 'no JavaScript or CSP errors').toEqual([])
  expect(external, 'no backend, ERP, model or remote assets').toEqual([])
})

