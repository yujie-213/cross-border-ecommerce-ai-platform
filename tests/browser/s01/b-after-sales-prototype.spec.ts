// Browser interaction only. All business records and AI outputs remain synthetic.
const root = path.resolve(import.meta.dirname, '../../..')
const entry = pathToFileURL(path.join(root, 'prototypes/b-after-sales/index.html')).href
const screenshots = path.join(root, 'docs/evidence/B-PROTOTYPE-REVISION-20261116/screenshots')
let errors: string[]
let external: string[]
test.beforeEach(async ({ page }) => {
  mkdirSync(screenshots, { recursive: true }); errors = []; external = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
  page.on('request', r => { if (!r.url().startsWith('file:')) external.push(r.url()) })
  await page.goto(entry)
})
test.afterEach(async () => {
  expect(errors, 'no JavaScript or CSP errors').toEqual([])
  expect(external, 'no API, ERP, model or external assets').toEqual([])
})
async function lab(page, label: string, value: string) {
  await page.getByRole('button', { name: '教学与异常演示', exact: true }).click()
  await page.getByRole('dialog').getByLabel(label, { exact: true }).selectOption(value)
}

