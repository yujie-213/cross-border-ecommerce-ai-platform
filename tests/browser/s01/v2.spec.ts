import { test, expect } from '../../../frontend/node_modules/@playwright/test/index.mjs'
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import path from 'node:path'
const root = path.resolve(import.meta.dirname, '../../..')
const privateDir = path.join(root, 'data/private/s01-v2-local')
const screenshots = path.join(root, 'docs/evidence/S01-V2/screenshots')

test('V2 READONLY: real full-range history, server filters, current rules, zero-source warning and responsive UI', async ({ page }) => {
  test.skip(process.env.S01_V2_READONLY_BROWSER !== 'true', 'Explicit real read-only V2 session required')
  test.setTimeout(120000)
  const session = JSON.parse(readFileSync(path.join(privateDir, 'session.json'), 'utf8'))
  const batch = JSON.parse(readFileSync(path.join(privateDir, 'read-only-batch.json'), 'utf8'))
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  mkdirSync(screenshots, { recursive: true })
  await page.goto('/')
  await page.getByRole('button', { name: '连接身份', exact: true }).first().click()
  await page.getByLabel('短期身份令牌').fill(session.token)
  await page.getByRole('button', { name: '连接会话', exact: true }).click()
  await expect(page.getByRole('heading', { name: '全量补货工作台', exact: true })).toBeVisible()
  await page.getByRole('row').filter({ hasText: batch.task.taskRef.taskId }).getByRole('button', { name: '打开批次' }).click()
  await expect(page.getByText('975', { exact: true })).toBeVisible()
  const search = page.getByLabel('SKU / 商品搜索', { exact: true })
  await search.fill('HL-CBL100-2M')
  await expect(page.getByRole('row').filter({ hasText: 'HL-CBL100-2M' })).toHaveCount(1)
  await page.getByRole('button', { name: '查看详情', exact: true }).click()
  await expect(page.getByRole('heading', { name: /HL-CBL100-2M/ })).toBeVisible()
  await expect(page.getByText('12 / 8 件', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '新建单品分析', exact: true })).toBeEnabled()
  await expect(page.getByRole('button', { name: '确认并提交 ERP 请购', exact: true })).toHaveCount(0)
  await page.screenshot({ path: path.join(screenshots, 'readonly-desktop.png'), fullPage: true })
  await search.fill('YF-SO-PZ-M')
  await expect(page.getByRole('row').filter({ hasText: 'YF-SO-PZ-M' })).toHaveCount(1)
  await page.getByRole('button', { name: '查看详情', exact: true }).click()
  await expect(page.getByText('ERP 为 0，原因待核实', { exact: true })).toBeVisible()
  await expect(page.getByRole('status').filter({ hasText: '该补货数量来自 ERP 现有建议记录' })).toContainText('该补货数量来自 ERP 现有建议记录，部分计算依据未验证。请核对采购条件及已有采购后人工确认。')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: path.join(screenshots, 'readonly-mobile.png'), fullPage: true })
  expect(errors).toEqual([])
  writeFileSync(path.join(privateDir, 'browser-readonly-result.json'), JSON.stringify({ result: 'PASS', batchId: batch.task.taskRef.taskId, pageErrors: errors, newModelCalls: 0, newBusinessMutations: 0 }, null, 2))
})
